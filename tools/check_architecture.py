#!/usr/bin/env python3
"""CI04: focused architecture regression checks, not a Kotlin parser or sandbox."""
import argparse
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PKG = "de.justify87.ladiesexplorer"
BASE = "app/src/main/java/" + PKG.replace(".", "/") + "/"
STORE = BASE + "core/CoreStore.kt"
APP = BASE + "LadiesApplication.kt"
VIDEO = BASE + "ui/GalleryVideo.kt"
ANDROID = "{http://schemas.android.com/apk/res/android}"

# Allow SDK map transport, not application HTTP.
HTTP = r"\b(?:okhttp3|retrofit2|ktor\.client|com\.android\.volley|java\.net|javax\.net|android\.webkit|HttpURLConnection|URLConnection|OkHttpClient|OkHttpNetworkFetcherFactory|KtorNetworkFetcherFactory|WebView|DownloadManager|openConnection|openStream|Socket|SSLSocket)\b"
HTTP_DEP = r"coil[-.]network[-.](?:okhttp|ktor)|com\.squareup\.(?:okhttp|retrofit)|io\.ktor|com\.android\.volley"
DB = r"\b(?:android\.database\.sqlite|androidx\.sqlite|androidx\.room|java\.sql|org\.sqlite|SQLiteDatabase|SQLiteOpenHelper|SupportSQLiteDatabase|SupportSQLiteOpenHelper|RoomDatabase|openOrCreateDatabase)\b"
DB_DEP = r"androidx[.:]room|androidx[.:]sqlite|org\.xerial|sqlite-jdbc|app\.cash\.sqldelight|com\.squareup\.sqldelight"
BRIDGE = r"\b(?:com\.sun\.jna|System\s*\.\s*loadLibrary|System\s*\.\s*load\s*\(|Runtime\s*\.\s*getRuntime\s*\(\s*\)\s*\.\s*load|external\s+fun|native\s+[\w<>\[\]]+\s+\w+\s*\()"
FACTORY = r"\bNetworkFetcher\s*\.\s*Factory\s*\("
PRIVATE = re.compile(r"(?:.*\.(?:har|har\.json|sqlite|sqlite3|sqlite-wal|sqlite-shm|sqlite3-wal|sqlite3-shm|db|db-wal|db-shm)|ladies-debug-.*\.txt|ladies-http-.*\.json|.*ladies-export.*\.zip)", re.I)


def issue(rule, path, message, line=None):
    return (rule, path, line, message)


# Mask comments and optionally literals without shifting positions; not a Kotlin parser.
LEXEME = re.compile(r'"""[\s\S]*?"""|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'|//[^\n]*|/\*')
LOCAL_OPTIONS = {
    "config": "no", "load-scripts": "no", "ytdl": "no",
    "autoload-files": "no", "access-references": "no",
    "demuxer": "lavf", "demuxer-lavf-o": "protocol_whitelist=file",
    "sub-auto": "no", "audio-file-auto": "no",
}


def masked(text, literals=False):
    """Blank lexical trivia without shifting lines; handle nested block comments."""
    parts = []
    end = 0
    while match := LEXEME.search(text, end):
        parts.append(text[end:match.start()])
        end = match.end()
        token = match.group()
        if token == "/*":
            depth = 1
            while depth and end < len(text):
                if text.startswith("/*", end):
                    depth += 1
                    end += 2
                elif text.startswith("*/", end):
                    depth -= 1
                    end += 2
                else:
                    end += 1
            token = text[match.start():end]
        if literals or token.startswith(("//", "/*")):
            parts.append(re.sub(r"[^\n]", " ", token))
        else:
            parts.append(token)
    parts.append(text[end:])
    return "".join(parts)


def source_file(path, text):
    errors = []
    code = masked(text, literals=True)

    def reject(rule, pattern, message):
        for match in re.finditer(pattern, code):
            errors.append(issue(rule, path, message, code.count("\n", 0, match.start()) + 1))

    reject("ARC-01", HTTP, "direct source transport or WebView")
    if path != APP:
        reject("ARC-01", FACTORY, "network fetcher outside application wiring")
        reject("ARC-01", r"\bcoil3\.network\.NetworkFetcher\b", "network fetcher outside application wiring")
    reject("ARC-02", DB, "database API outside Rust")
    if path != STORE:
        reject("ARC-03", r"\bLadiesCore(?:Interface)?\b", "native engine must remain private to CoreStore")
    reject("ARC-06", BRIDGE, "alternative native bridge")
    if path.startswith(BASE + "core/") or re.search(r"(?m)^\s*package\s+" + re.escape(PKG) + r"\.core(?:\.|\s|$)", code):
        reject("ARC-05", re.escape(PKG) + r"\.ui\b", "core infrastructure depends on UI")
        reject("ARC-05", r"\b(?:androidx\.compose|androidx\.lifecycle\.ViewModel)\b", "UI dependency in core infrastructure")
    if path != VIDEO:
        reject("ARC-07", r"\b(?:dev\.jdtech\.mpv|MPVLib)\b", "libmpv outside local gallery adapter")
    # Generated-file marker is intentionally checked before stripping comments.
    if re.search(r"(?im)^\s*(?://|/\*|\*)\s*.*(?:generated by uniffi|autogenerated by uniffi|autogenerated by the uniffi)", text) or re.search(r"\b(?:class|interface)\s+LadiesCore(?:Interface)?\b", code):
        errors.append(issue("ARC-04", path, "generated UniFFI engine source must not be committed"))
    return errors


def wiring(app, store, video):
    errors = []
    app, store, video = (masked(s) for s in (app, store, video))
    app_code, store_code, video_code = (masked(s, literals=True) for s in (app, store, video))
    # Match structure independent of formatting; JVM tests check compiled signatures.
    if not re.search(r"RustImageNetworkClient\s*\(\s*\w+\s*::\s*loadDisplayImage\s*\)", app_code) or len(re.findall(FACTORY, app_code)) != 1:
        errors.append(issue("ARC-01", APP, "exactly one Coil network adapter must delegate to Rust"))
    if not re.search(r"\bprivate\s+val\s+\w+\s*:\s*LadiesCore\b", store_code):
        errors.append(issue("ARC-03", STORE, "CoreStore engine must be private"))
    if not re.search(r"\bLadiesCore\s*\(", store_code):
        errors.append(issue("ARC-03", STORE, "CoreStore must own the native engine"))
    if not re.search(r"\.\s*loadDisplayVideo\s*\(", video_code):
        errors.append(issue("ARC-07", VIDEO, "gallery must obtain remote bytes through CoreStore"))
    # Require unique option pairs and reject overrides outside the checked loop.
    for name, value in LOCAL_OPTIONS.items():
        pairs = re.findall(r'"' + re.escape(name) + r'"\s+to\s+"([^"]*)"', video)
        if pairs != [value]:
            errors.append(issue("ARC-07", VIDEO, f"local player requires one {name}={value} option"))
        if re.search(r'\.\s*(?:setOption\w*|setProperty\w*)\s*\(\s*"' + re.escape(name) + r'"', video):
            errors.append(issue("ARC-07", VIDEO, f"unexpected override of {name}"))
    if not re.search(r"\.\s*setOptionString\s*\(", video_code):
        errors.append(issue("ARC-07", VIDEO, "local player options must be applied"))
    if not re.search(r'\.\s*command\s*\(\s*arrayOf\s*\(\s*"loadfile"\s*,\s*\w+\s*\.\s*file\s*\.\s*absolutePath\s*,\s*"replace"\s*\)\s*\)', video) or video.count('"loadfile"') != 1:
        errors.append(issue("ARC-07", VIDEO, "player must receive only the validated local file"))
    return errors


def tracked_paths(paths):
    errors = []
    for path in paths:
        p = PurePosixPath(path)
        if PRIVATE.fullmatch(p.name) or "raw_profiles" in p.parts or ("ladies_data" in p.parts and "media" in p.parts):
            errors.append(issue("ARC-08", path, "private export/database/archive path must not be tracked"))
        if path.startswith("app/src/") and (p.suffix in {".so", ".aar", ".udl"} or p.name in {"ladies_core.kt", "uniffi.kt"}):
            errors.append(issue("ARC-04", path, "native engine/bindings must be generated, not vendored"))
        if (len(p.parts) == 1 or path.startswith("app/src/")) and p.name in {"package.json", "requirements.txt", "pyproject.toml", "manage.py", "Dockerfile"}:
            errors.append(issue("ARC-06", path, "unexpected application backend/runtime manifest"))
        if path.startswith("app/src/") and p.suffix in {".py", ".js", ".ts"}:
            errors.append(issue("ARC-06", path, "unexpected application runtime source"))
    return errors


def dependency_file(path, text):
    errors = []
    for n, line in enumerate(masked(text).splitlines(), 1):
        for rule, pattern, message in (
            ("ARC-01", HTTP_DEP, "direct HTTP dependency"),
            ("ARC-02", DB_DEP, "Kotlin-side database dependency"),
            ("ARC-06", r"io\.ktor|org\.springframework|io\.netty|javalin|nanohttpd", "alternative server/runtime dependency"),
        ):
            if re.search(pattern, line, re.I):
                errors.append(issue(rule, path, message, n))
    return errors


def check_source(root):
    paths = subprocess.check_output(["git", "ls-files", "-z"], cwd=root, timeout=30).decode().split("\0")[:-1]
    errors = tracked_paths(paths)
    for path in paths:
        p = PurePosixPath(path)
        if p.suffix in {".kt", ".java"} and path.startswith("app/src/"):
            # Only the source-set name, not arbitrary package names, determines exclusion.
            variant = p.parts[2]
            if re.fullmatch(r"(?:test|androidTest)(?:[A-Z][A-Za-z0-9]*)?", variant):
                continue
            errors += source_file(path, (root / path).read_text(encoding="utf-8"))
        if p.name.endswith(".gradle.kts") or p.name.endswith(".gradle") or path == "gradle/libs.versions.toml":
            errors += dependency_file(path, (root / path).read_text(encoding="utf-8"))
    errors += wiring(*[(root / p).read_text(encoding="utf-8") for p in (APP, STORE, VIDEO)])
    return errors


PROVIDER_NAME = PKG + ".DiagnosticFileProvider"
PATH_RESOURCE = "xml/diagnostic_file_paths"


def qualified_name(name, package):
    if name.startswith("."):
        return package + name
    if "." not in name:
        return package + "." + name
    return name


def manifest_errors(xml):
    root = ET.fromstring(xml)
    errors = []
    label = "APK/AndroidManifest.xml"

    def fail(message):
        errors.append(issue("ARC-08", label, message))

    package = root.get("package", "")
    if package != PKG + ".debug":
        fail("expected debug application ID")
    app = root.find("application")
    if app is None:
        return errors + [issue("ARC-08", label, "missing application")]
    if app.get(ANDROID + "allowBackup") != "false":
        fail("private data backup must be disabled")
    allowed = {"android.permission.INTERNET", "android.permission.ACCESS_NETWORK_STATE",
               "android.permission.ACCESS_WIFI_STATE", package + ".DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION"}
    permissions = {el.get(ANDROID + "name") for el in root if el.tag.startswith("uses-permission")}
    for name in sorted(permissions - allowed, key=str):
        fail("unexpected permission: " + str(name))
    if "android.permission.INTERNET" not in permissions:
        fail("required Internet permission missing")
    receiver_permission = package + ".DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION"
    if receiver_permission in permissions and not any(
            el.get(ANDROID + "name") == receiver_permission
            and el.get(ANDROID + "protectionLevel") in {"signature", "0x00000002", "0x2", "2"}
            for el in root.findall("permission")):
        fail("AndroidX receiver permission must be signature protected")
    providers = []
    for el in app:
        if el.tag not in {"activity", "activity-alias", "service", "receiver", "provider"}:
            continue
        name = qualified_name(el.get(ANDROID + "name", ""), package)
        exported = el.get(ANDROID + "exported")
        if exported not in {"true", "false", None} or (exported is None and el.find("intent-filter") is not None):
            fail("ambiguous exported component: " + name)
        if exported == "true":
            launcher = el.tag == "activity" and name == PKG + ".MainActivity"
            debug_host = el.tag == "activity" and name in {"androidx.activity.ComponentActivity", "androidx.compose.ui.tooling.PreviewActivity"} and app.get(ANDROID + "debuggable") == "true"
            profile = el.tag == "receiver" and name == "androidx.profileinstaller.ProfileInstallReceiver" and el.get(ANDROID + "permission") == "android.permission.DUMP"
            if not (launcher or debug_host or profile):
                fail("unexpected exported component: " + name)
        if el.tag == "provider":
            has_paths = any(m.get(ANDROID + "name") == "android.support.FILE_PROVIDER_PATHS" for m in el.findall("meta-data"))
            grants = el.get(ANDROID + "grantUriPermissions") not in {None, "false"} or el.find("grant-uri-permission") is not None
            if name == PROVIDER_NAME:
                providers.append(el)
            elif has_paths or grants or name.endswith(".FileProvider"):
                fail("unexpected URI-grant/FileProvider: " + name)
    if len(providers) != 1:
        fail("expected exactly one diagnostic provider")
    else:
        provider = providers[0]
        if (provider.get(ANDROID + "exported") != "false"
                or provider.get(ANDROID + "grantUriPermissions") != "true"
                or provider.get(ANDROID + "authorities") != package + ".fileprovider"
                or provider.find("grant-uri-permission") is not None
                or provider.find("path-permission") is not None):
            fail("diagnostic provider must be private and explicitly grant scoped URIs")
        meta = provider.findall("meta-data")
        if len(meta) != 1 or meta[0].get(ANDROID + "name") != "android.support.FILE_PROVIDER_PATHS" or not meta[0].get(ANDROID + "resource"):
            fail("diagnostic provider must reference the reviewed path resource")
    return errors


def provider_reference(xml):
    root = ET.fromstring(xml)
    for provider in root.findall("application/provider"):
        if qualified_name(provider.get(ANDROID + "name", ""), root.get("package", "")) == PROVIDER_NAME:
            for meta in provider.findall("meta-data"):
                if meta.get(ANDROID + "name") == "android.support.FILE_PROVIDER_PATHS":
                    return meta.get(ANDROID + "resource")
    return None


def provider_resource_files(reference, table):
    """Resolve apkanalyzer's symbolic or compiled ref using this APK's aapt2 table.

    Reject aliases, missing/duplicate entries and any non-file configuration.
    All file-valued configurations are checked, not just res/xml/default.
    """
    package = None
    entries = []
    active = None
    for line in table.splitlines():
        if match := re.match(r"\s*Package name=(\S+)", line):
            package, active = match[1], None
        elif match := re.match(r"\s*resource (0x[0-9a-fA-F]+) (\S+)", line):
            active = None
            name = match[2]
            if name == PATH_RESOURCE and package == PKG + ".debug":
                active = (int(match[1], 16), [])
                entries.append(active)
        elif re.match(r"\s*type ", line):
            active = None
        elif active is not None and re.match(r"\s*\([^)]*\)\s+", line):
            match = re.fullmatch(r"\s*\([^)]*\)\s+\(file\)\s+(\S+)(?:\s+.*)?", line)
            if not match:
                raise ValueError("diagnostic path resource has a non-file configuration")
            active[1].append(match[1])
    if len(entries) != 1:
        raise ValueError("diagnostic path resource missing or ambiguous in APK table")
    resource_id, files = entries[0]
    if reference not in {"@" + PATH_RESOURCE, "@" + PKG + ".debug:" + PATH_RESOURCE}:
        match = re.fullmatch(r"@(?:ref/)?(0x[0-9a-fA-F]{8})", reference or "")
        if not match or int(match[1], 16) != resource_id:
            raise ValueError(f"diagnostic provider reference {reference!r} is not {resource_id:#010x} ({PATH_RESOURCE})")
    if not files or any(not re.fullmatch(r"res/[^/]+/[^/]+\.xml", path) for path in files):
        raise ValueError("diagnostic path resource has no reviewed APK XML files")
    return sorted(set(files))


def provider_errors(xml):
    root = ET.fromstring(xml)
    if (root.tag == "paths" and len(root) == 1 and root[0].tag == "cache-path"
            and root[0].attrib == {"name": "diagnostic-exports", "path": "diagnostic-exports/"}
            and len(root[0]) == 0):
        return []
    return [issue("ARC-08", "APK/diagnostic_file_paths.xml", "only diagnostic-exports cache subdirectory may be shared")]


def native_errors(entries):
    required = {"lib/arm64-v8a/libladies_core.so", "lib/arm64-v8a/libjnidispatch.so"}
    missing = required - set(entries)
    return [issue("ARC-04", "APK", "missing native bridge: " + path) for path in sorted(missing)]


def check_apk(apk, analyzer, aapt2):
    def xml(*args):
        return subprocess.check_output([analyzer, *args, str(apk)], timeout=90)
    with zipfile.ZipFile(apk) as archive:
        entries = set(archive.namelist())
    errors = native_errors(entries)
    manifest = xml("manifest", "print")
    errors += manifest_errors(manifest)
    try:
        table = subprocess.check_output([aapt2, "dump", "resources", str(apk)], timeout=90, text=True)
        reference = provider_reference(manifest)
        files = provider_resource_files(reference, table)
        print(f"Diagnostic provider: {reference} -> {', '.join(files)}")
        for path in files:
            if path not in entries:
                raise ValueError(f"referenced path XML missing from APK: {path}")
            errors += provider_errors(xml("resources", "xml", "--file", "/" + path))
    except ValueError as error:
        errors.append(issue("ARC-08", "APK/resources.arsc", str(error)))
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--apk", type=Path)
    parser.add_argument("--apkanalyzer", default="apkanalyzer")
    parser.add_argument("--aapt2", default="aapt2")
    args = parser.parse_args()
    errors = check_apk(args.apk, args.apkanalyzer, args.aapt2) if args.apk else check_source(args.root)
    for rule, path, line, message in errors:
        location = f"{path}:{line}" if line else path
        print(f"{rule} {location}: {message}", file=sys.stderr)
    if errors:
        return 1
    print("Architecture APK checks passed" if args.apk else "Architecture source checks passed (static regression checks, not runtime proof)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
