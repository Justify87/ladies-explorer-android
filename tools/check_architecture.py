#!/usr/bin/env python3
"""CI04: focused architecture regression checks, not a Kotlin parser or sandbox."""
import argparse
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PKG = "de.justify87.ladiesexplorer"
BASE = "app/src/main/java/" + PKG.replace(".", "/") + "/"
STORE = BASE + "core/CoreStore.kt"
APP = BASE + "LadiesApplication.kt"
VIDEO = BASE + "ui/GalleryVideo.kt"
ANDROID = "{http://schemas.android.com/apk/res/android}"

# Preserve the former source-HTTP gate; allow SDK map transport, not app HTTP.
HTTP = r"\b(?:okhttp3|retrofit2|ktor\.client|com\.android\.volley|java\.net|javax\.net|android\.webkit|HttpURLConnection|URLConnection|OkHttpClient|OkHttpNetworkFetcherFactory|KtorNetworkFetcherFactory|WebView|DownloadManager|openConnection|openStream|Socket|SSLSocket)\b"
HTTP_DEP = r"coil[-.]network[-.](?:okhttp|ktor)|com\.squareup\.(?:okhttp|retrofit)|io\.ktor|com\.android\.volley"
DB = r"\b(?:android\.database\.sqlite|androidx\.sqlite|androidx\.room|java\.sql|org\.sqlite|SQLiteDatabase|SQLiteOpenHelper|SupportSQLiteDatabase|SupportSQLiteOpenHelper|RoomDatabase|openOrCreateDatabase)\b"
DB_DEP = r"androidx[.:]room|androidx[.:]sqlite|org\.xerial|sqlite-jdbc|app\.cash\.sqldelight|com\.squareup\.sqldelight"
BRIDGE = r"\b(?:com\.sun\.jna|System\s*\.\s*loadLibrary|System\s*\.\s*load\s*\(|Runtime\s*\.\s*getRuntime\s*\(\s*\)\s*\.\s*load|external\s+fun|native\s+[\w<>\[\]]+\s+\w+\s*\()"
FACTORY = r"\bNetworkFetcher\s*\.\s*Factory\s*\("
PRIVATE = re.compile(r"(?:.*\.(?:har|har\.json|sqlite|sqlite3|sqlite-wal|sqlite-shm|sqlite3-wal|sqlite3-shm|db|db-wal|db-shm)|ladies-debug-.*\.txt|ladies-http-.*\.json|.*ladies-export.*\.zip)", re.I)


def issue(rule, path, message, line=None):
    return (rule, path, line, message)


def source_file(path, text):
    errors = []
    for n, line in enumerate(text.splitlines(), 1):
        def reject(rule, pattern, message):
            if re.search(pattern, line):
                errors.append(issue(rule, path, message, n))

        reject("ARC-01", HTTP, "direct source transport or WebView")
        if path != APP:
            reject("ARC-01", FACTORY, "network fetcher outside application wiring")
        reject("ARC-02", DB, "database API outside Rust")
        if path != STORE:
            reject("ARC-03", r"\bLadiesCore(?:Interface)?\b", "native engine must remain private to CoreStore")
        reject("ARC-06", BRIDGE, "alternative native bridge")
        if re.search(r"(?m)^\s*package\s+" + re.escape(PKG) + r"\.core(?:\.|\s|$)", text):
            reject("ARC-05", re.escape(PKG) + r"\.ui\b", "core infrastructure depends on UI")
            reject("ARC-05", r"\b(?:androidx\.compose|androidx\.lifecycle\.ViewModel)\b", "UI dependency in core infrastructure")
        if path != VIDEO:
            reject("ARC-07", r"\b(?:dev\.jdtech\.mpv|MPVLib)\b", "libmpv outside local gallery adapter")
    if re.search(r"(?im)^\s*(?://|/\*|\*)\s*.*(?:generated by uniffi|autogenerated by uniffi|autogenerated by the uniffi)", text) or re.search(r"\b(?:class|interface)\s+LadiesCore(?:Interface)?\b", text):
        errors.append(issue("ARC-04", path, "generated UniFFI engine source must not be committed"))
    return errors


def wiring(app, store, video):
    errors = []
    for rule, path, text, pattern, message in (
        ("ARC-01", APP, app, r"RustImageNetworkClient\s*\(\s*coreStore\s*::\s*loadDisplayImage\s*\)", "Coil must delegate to Rust"),
        ("ARC-03", STORE, store, r"\bprivate\s+val\s+engine\s*:\s*LadiesCore\b", "CoreStore engine must be private"),
        ("ARC-07", VIDEO, video, r"app\.coreStore\.loadDisplayVideo\s*\(", "gallery must obtain remote bytes through CoreStore"),
        ("ARC-07", VIDEO, video, r'"demuxer-lavf-o"\s+to\s+"protocol_whitelist=file"', "libmpv local protocol restriction required"),
        ("ARC-07", VIDEO, video, r'player\.command\s*\(\s*arrayOf\s*\(\s*"loadfile"\s*,\s*source\.file\.absolutePath\s*,\s*"replace"\s*\)\s*\)', "player must receive the validated local file"),
    ):
        if not re.search(pattern, text):
            errors.append(issue(rule, path, message))
    if len(re.findall(FACTORY, app)) != 1:
        errors.append(issue("ARC-01", APP, "expected exactly one configured Coil network fetcher"))
    # Check every loadfile literal, not only the known safe call.
    if video.count('"loadfile"') != 1:
        errors.append(issue("ARC-07", VIDEO, "unexpected additional player load path"))
    return errors


def tracked_paths(paths):
    errors = []
    for path in paths:
        p = PurePosixPath(path)
        if PRIVATE.fullmatch(p.name) or "raw_profiles" in p.parts or ("ladies_data" in p.parts and "media" in p.parts):
            errors.append(issue("ARC-08", path, "private export/database/archive path must not be tracked"))
        if path.startswith("app/src/") and (p.suffix in {".so", ".aar", ".udl"} or p.name in {"ladies_core.kt", "uniffi.kt"}):
            errors.append(issue("ARC-04", path, "native engine/bindings must be generated, not vendored"))
        if (len(p.parts) == 1 or path.startswith("app/src/")) and p.name in {"package.json", "requirements.txt", "pyproject.toml", "manage.py", "Dockerfile"}:
            errors.append(issue("ARC-06", path, "unexpected application backend/runtime manifest"))
        if path.startswith("app/src/") and p.suffix in {".py", ".js", ".ts"}:
            errors.append(issue("ARC-06", path, "unexpected application runtime source"))
    return errors


def dependency_file(path, text):
    errors = []
    for n, line in enumerate(text.splitlines(), 1):
        for rule, pattern, message in (
            ("ARC-01", HTTP_DEP, "direct HTTP dependency"),
            ("ARC-02", DB_DEP, "Kotlin-side database dependency"),
            ("ARC-06", r"io\.ktor|org\.springframework|io\.netty|javalin|nanohttpd", "alternative server/runtime dependency"),
        ):
            if re.search(pattern, line, re.I):
                errors.append(issue(rule, path, message, n))
    return errors


def check_source(root):
    paths = subprocess.check_output(["git", "ls-files", "-z"], cwd=root, timeout=30).decode().split("\0")[:-1]
    errors = tracked_paths(paths)
    for path in paths:
        p = PurePosixPath(path)
        if p.suffix in {".kt", ".java"} and path.startswith("app/src/"):
            # Only the source-set name, not arbitrary package names, determines exclusion.
            variant = p.parts[2]
            if variant.startswith(("test", "androidTest")):
                continue
            errors += source_file(path, (root / path).read_text(encoding="utf-8"))
        if p.name.endswith(".gradle.kts") or p.name.endswith(".gradle") or path == "gradle/libs.versions.toml":
            errors += dependency_file(path, (root / path).read_text(encoding="utf-8"))
    errors += wiring(*[(root / p).read_text(encoding="utf-8") for p in (APP, STORE, VIDEO)])
    return errors


def manifest_errors(xml):
    root = ET.fromstring(xml)
    errors = []
    label = "APK/AndroidManifest.xml"
    def fail(message):
        errors.append(issue("ARC-08", label, message))
    package = root.get("package")
    if package != PKG + ".debug":
        fail("expected debug application ID")
    app = root.find("application")
    if app is None:
        return errors + [issue("ARC-08", label, "missing application")]
    if app.get(ANDROID + "allowBackup") != "false":
        fail("private data backup must be disabled")
    # MapLibre network state, normal Internet; AndroidX receiver signature permission.
    allowed = {"android.permission.INTERNET", "android.permission.ACCESS_NETWORK_STATE",
               package + ".DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION"}
    permissions = {el.get(ANDROID + "name") for el in root if el.tag.startswith("uses-permission")}
    for name in sorted(permissions - allowed, key=str):
        fail("unexpected permission: " + str(name))
    if "android.permission.INTERNET" not in permissions:
        fail("required Internet permission missing")
    receiver_permission = package + ".DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION"
    if receiver_permission in permissions and not any(
            el.get(ANDROID + "name") == receiver_permission
            and el.get(ANDROID + "protectionLevel") in {"signature", "0x00000002", "0x2", "2"}
            for el in root.findall("permission")):
        fail("AndroidX receiver permission must be signature protected")
    provider = None
    for el in app:
        if el.tag not in {"activity", "activity-alias", "service", "receiver", "provider"}:
            continue
        name = el.get(ANDROID + "name", "")
        if name.startswith("."):
            name = package + name
        exported = el.get(ANDROID + "exported")
        # target SDK >= 29: providers are private by default, other components
        # with intent filters may not acquire an implicit export.
        if exported not in {"true", "false", None} or (exported is None and el.find("intent-filter") is not None):
            fail("ambiguous exported component: " + name)
        if exported == "true":
            launcher = el.tag == "activity" and name == PKG + ".MainActivity"
            # Compose debug-only test/preview host entries, never app data providers.
            debug_host = el.tag == "activity" and name in {"androidx.activity.ComponentActivity", "androidx.compose.ui.tooling.PreviewActivity"} and app.get(ANDROID + "debuggable") == "true"
            profile = el.tag == "receiver" and name == "androidx.profileinstaller.ProfileInstallReceiver" and el.get(ANDROID + "permission") == "android.permission.DUMP"
            if not (launcher or debug_host or profile):
                fail("unexpected exported component: " + name)
        if name == PKG + ".DiagnosticFileProvider" and el.tag == "provider":
            provider = el
    if provider is None:
        fail("missing diagnostic provider")
    else:
        if (provider.get(ANDROID + "exported") != "false"
                or provider.get(ANDROID + "grantUriPermissions") != "true"
                or provider.get(ANDROID + "authorities") != package + ".fileprovider"):
            fail("diagnostic provider must be private and explicitly grant scoped URIs")
        meta = provider.findall("meta-data")
        if len(meta) != 1 or meta[0].get(ANDROID + "name") != "android.support.FILE_PROVIDER_PATHS" or meta[0].get(ANDROID + "resource") != "@xml/diagnostic_file_paths":
            fail("diagnostic provider must reference the reviewed path resource")
    return errors


def provider_errors(xml):
    root = ET.fromstring(xml)
    if (root.tag == "paths" and len(root) == 1 and root[0].tag == "cache-path"
            and root[0].attrib == {"name": "diagnostic-exports", "path": "diagnostic-exports/"}):
        return []
    return [issue("ARC-08", "APK/diagnostic_file_paths.xml", "only diagnostic-exports cache subdirectory may be shared")]


def native_errors(entries):
    required = {"lib/arm64-v8a/libladies_core.so", "lib/arm64-v8a/libjnidispatch.so"}
    missing = required - set(entries)
    return [issue("ARC-04", "APK", "missing native bridge: " + path) for path in sorted(missing)]


def check_apk(apk, analyzer):
    def xml(*args):
        return subprocess.check_output([analyzer, *args, str(apk)], timeout=90)
    with zipfile.ZipFile(apk) as archive:
        errors = native_errors(archive.namelist())
    errors += manifest_errors(xml("manifest", "print"))
    errors += provider_errors(xml("resources", "xml", "--file", "/res/xml/diagnostic_file_paths.xml"))
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apk", type=Path)
    parser.add_argument("--apkanalyzer", default="apkanalyzer")
    args = parser.parse_args()
    errors = check_apk(args.apk, args.apkanalyzer) if args.apk else check_source(ROOT)
    for rule, path, line, message in errors:
        location = f"{path}:{line}" if line else path
        print(f"{rule} {location}: {message}", file=sys.stderr)
    if errors:
        return 1
    print("Architecture APK checks passed" if args.apk else "Architecture source checks passed (static regression checks, not runtime proof)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
